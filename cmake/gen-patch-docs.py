#!/usr/bin/env python3
"""
Patch reference from the registry (restructuring plan 4.8, DOC-2): reads every PatchDescriptor row
in sysdll/patches/ and sysdll/diagnostics/, the install order in sysdll/core/PatchList.cpp and the
PolicyOff rows of the title profiles, and writes docs/patches.md.

    gen-patch-docs.py <repo>            write docs/patches.md
    gen-patch-docs.py <repo> --check    exit 1 when docs/patches.md is not what the code says
"""
import pathlib
import re
import sys

STR = r'"((?:[^"\\]|\\.)*)"'
ROW = re.compile(r"\{\s*" + STR + r",\s*" + STR + r",\s*([A-Z_| ]+?),\s*((?:" + STR + r"\s*)+),\s*(\w+)")
TRACE = re.compile(r"TRACE_IMPORT\(\s*" + STR + r",\s*" + STR + r",\s*(\d+),\s*\w+,\s*((?:" + STR + r"\s*)+)\)")
TABLE = re.compile(r"const PatchTable (\w+) = PATCH_TABLE\(kRows\);")
POLICY = re.compile(r"\{\s*" + STR + r",\s*" + STR + r"\s*\}")
PROFILE_NAME = re.compile(r'kTitleProfile\d+ = \{\s*"([^"]+)"')
PHASES = {"ON_KERNEL": "kernel", "ON_EARLY": "early", "ON_TITLE": "title"}


def strings(text):
    return "".join(re.findall(STR, text))


def rows_of(path):
    text = path.read_text()
    table = TABLE.search(text)
    body = text[text.index("kRows[] = {"):table.start()] if table else ""
    rows = []
    for m in ROW.finditer(body):
        phases = ", ".join(PHASES[p.strip()] for p in m.group(3).split("|"))
        rows.append((m.start(), (m.group(1), m.group(2), phases, strings(m.group(4)))))
    for m in TRACE.finditer(body):
        rows.append((m.start(), (m.group(1), m.group(2), "title", strings(m.group(4)))))
    return (table.group(1) if table else None), [row for _, row in sorted(rows)]


def generate(repo):
    sysdll = repo / "sysdll"
    tables = {}
    for layer in ("patches", "diagnostics"):
        for path in sorted((sysdll / layer).glob("*.cpp")):
            name, rows = rows_of(path)
            if name:
                tables[name] = (f"{layer}/{path.name}", layer == "diagnostics", rows)
    order = re.findall(r"&(k\w+Patches),", (sysdll / "core/PatchList.cpp").read_text())
    missing = set(tables) - set(order)
    if missing:
        sys.exit(f"gen-patch-docs: tables not in core/PatchList.cpp: {sorted(missing)}")
    policy = {}
    for path in sorted((sysdll / "title").glob("TitleProfile[0-9]*.cpp")):
        text = path.read_text()
        build = PROFILE_NAME.search(text).group(1)
        block = text[text.index("kPolicyOff[] = {"):]
        block = block[:block.index("};")]
        for patch, reason in POLICY.findall(block):
            policy.setdefault(patch, []).append(f"{build}: {reason}")

    out = ["# Patch reference", "",
           "Generated by `cmake/gen-patch-docs.py` from the registry rows; do not edit by hand (the",
           "build fails when this file is stale). Switch names go in `1vs100Reborn.disable`",
           "(see `PATCHES.md`). A patch whose site a build does not have reports `skipped, why=site`;",
           "the \"Off for\" column lists the builds whose profile turns it off on purpose (`why=build`).",
           ""]
    for flavour, diag in (("Production", False), ("Diagnostics build only (`xdk-diagnostics` preset)", True)):
        out += [f"## {flavour}", "",
                "| # | Manifest id | Switch | Phase | Off for | What it does | File |",
                "|---|-------------|--------|-------|---------|--------------|------|"]
        n = 0
        for table in order:
            if table not in tables or tables[table][1] != diag:
                continue
            file, _, rows = tables[table]
            for pid, switch, phases, summary in rows:
                n += 1
                off = "<br>".join(policy.get(pid, [])) or "-"
                out.append(f"| {n} | `{pid}` | `{switch}` | {phases} | {off} | {summary} | `{file}` |")
        out.append("")
    return "\n".join(out)


def main():
    repo = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    target = repo / "docs" / "patches.md"
    text = generate(repo)
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            print("gen-patch-docs: docs/patches.md is stale; run cmake/gen-patch-docs.py")
            return 1
        print("gen-patch-docs: OK")
        return 0
    target.write_text(text)
    print(f"gen-patch-docs: wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

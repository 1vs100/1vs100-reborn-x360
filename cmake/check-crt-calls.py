#!/usr/bin/env python3
"""
Audit a linked 1vs100Reborn .map file for LIBCMT/LIBCPMT symbols pulled into
the final image, and fail the build if any weren't already known-necessary
(tracked in a checked-in baseline file, cmake/crt-baseline.txt).

WHY THIS EXISTS (2026-09-11): this loader is /MT-linked and its hook
trampolines run on foreign (title) threads, not just its own. Its own
statically-linked CRT lazily allocates per-thread state (_tiddata) the
first time ANY CRT function is touched on a given thread, via a
KeTlsAlloc'd TLS index - and that index has been observed to collide with
XUI's own, independently-allocated dynamic TLS index, making XUI's
"defer visual attach" gate read garbage as non-zero on whatever thread
touched the CRT first. Root cause and full story: `docs/xui.md` / `docs/HISTORY.md`.

`_DllMainCRTStartup` itself unavoidably pulls in a large amount of CRT
startup machinery on its own (heap init, _getptd, __tlsindex, even
strrchr for argv parsing) - none of that is dangerous by itself, since it
runs exactly once, on the module-load thread, during DLL_PROCESS_ATTACH.
The danger is code OUR OWN hook trampolines reach that lazily touches that
same machinery again, later, from an arbitrary (potentially title) thread.
The two real bugs found this way so far: a directly-called
_vsnprintf/strlen/strstr, and a *compiler-inserted* 64-bit-divide-helper
call from unwary ULONGLONG arithmetic in the fix for the first one.

A map file has no call graph, so there's no way to mechanically tell
"pulled in for one-time startup" apart from "reachable from a hook" by
symbol name alone. Instead of guessing, this compares the CURRENT set of
pulled-in LIBCMT/LIBCPMT symbols against a checked-in baseline of what is
already known necessary. Anything NEW fails the build: either the new code
introduced a CRT touch and needs a hand-rolled, CRT-free replacement (see
platform/Format.cpp for the pattern), or - if it is genuinely load-time-only and has been
manually audited as safe - re-run with --update-baseline and say why in a
comment in the baseline file.
"""
import argparse
import pathlib
import sys

LIB_PREFIXES = ("libcmt:", "libcpmt:")


def extract(map_path: pathlib.Path) -> set:
    syms = set()
    with map_path.open("r", errors="replace") as f:
        for line in f:
            fields = line.split()
            if len(fields) < 3:
                continue
            last = fields[-1]
            if not last.lower().startswith(LIB_PREFIXES):
                continue
            if not last.lower().endswith(".obj"):
                continue
            # Line shape: <seg:off>  <symbol>  <rva>  [f]  <Lib:Object>
            # symbol is always the token right after the segment:offset address.
            syms.add(fields[1])
    return syms


def load_baseline(path: pathlib.Path) -> set:
    if not path.exists():
        return set()
    syms = set()
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            syms.add(line)
    return syms


def write_baseline(path: pathlib.Path, syms: set) -> None:
    header = (
        "# Known-necessary LIBCMT/LIBCPMT symbols pulled into 1vs100Reborn.xex.\n"
        "# Generated by cmake/check-crt-calls.py --update-baseline. Do not hand-edit\n"
        "# without auditing WHY each new symbol is safe - see that script's docstring\n"
        "# and `docs/xui.md` / `docs/HISTORY.md` (2026-09-11) for what this guards against.\n"
    )
    path.write_text(header + "\n".join(sorted(syms)) + "\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--map", required=True, type=pathlib.Path)
    ap.add_argument("--baseline", required=True, type=pathlib.Path)
    ap.add_argument(
        "--update-baseline",
        action="store_true",
        help="rewrite the baseline to match the current map (only after manually "
        "auditing that every new symbol is load-time-only and safe)",
    )
    args = ap.parse_args()

    if not args.map.exists():
        print(f"check-crt-calls: map file not found: {args.map}", file=sys.stderr)
        return 1

    current = extract(args.map)

    if args.update_baseline:
        write_baseline(args.baseline, current)
        print(f"check-crt-calls: baseline updated with {len(current)} symbols")
        return 0

    baseline = load_baseline(args.baseline)
    new = sorted(current - baseline)
    if new:
        print(
            "check-crt-calls: FAILED - new LIBCMT/LIBCPMT symbols pulled into "
            "1vs100Reborn.xex that are not in the baseline:",
            file=sys.stderr,
        )
        for s in new:
            print(f"  + {s}", file=sys.stderr)
        print(file=sys.stderr)
        print(
            "This is exactly the shape of the 2026-09-11 TLS-collision bug (and its\n"
            "64-bit-divide-helper regression): a CRT call reachable from a title thread\n"
            "lazily allocates per-thread state that collides with XUI's own dynamic TLS\n"
            "index. Find what change introduced this symbol and replace it with a\n"
            "CRT-free equivalent (see platform/Format.cpp). If it is genuinely load-time-only code and\n"
            f"has been manually audited as safe, re-run with --update-baseline and record\n"
            f"why in a comment in {args.baseline}.",
            file=sys.stderr,
        )
        return 1

    print(f"check-crt-calls: OK ({len(current)} known LIBCMT/LIBCPMT symbols, no new ones)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
